import { randomBytes, randomUUID } from "node:crypto";
import { NextResponse } from "next/server";
import type { NextRequest } from "next/server";

const UUID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
const MUTATING_METHODS = new Set(["POST", "PUT", "PATCH", "DELETE"]);

function buildContentSecurityPolicy(nonce: string) {
  const directives = [
    "default-src 'self'",
    `script-src 'self' 'nonce-${nonce}' 'strict-dynamic' https://www.googletagmanager.com https://www.google-analytics.com`,
    "script-src-attr 'none'",
    // The UI uses inline style attributes for calculated widths/colors; script execution remains nonce-based.
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob:",
    "font-src 'self' data:",
    "connect-src 'self' https://*.supabase.co wss://*.supabase.co https://www.google-analytics.com https://analytics.google.com https://region1.google-analytics.com https://www.googletagmanager.com",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
    "frame-src 'none'",
    "worker-src 'self' blob:",
    "manifest-src 'self'",
    "upgrade-insecure-requests"
  ];
  return directives.join("; ");
}

function privateHeaders(response: NextResponse) {
  response.headers.set("Cache-Control", "no-store, no-cache, must-revalidate, private");
  response.headers.set("Pragma", "no-cache");
  response.headers.set("Expires", "0");
  response.headers.set("Cross-Origin-Resource-Policy", "same-origin");
}

/**
 * Applies a per-request CSP nonce and secure cache defaults.
 * Request IDs are generated by the server; caller-supplied IDs are never authoritative.
 * No Access-Control-Allow-Origin header is emitted: browser APIs remain same-origin only.
 */
function applySecurityHeaders(
  response: NextResponse,
  options: { requestId: string; pathname: string; isPrivatePath: boolean; nonce: string | null }
) {
  const { requestId, pathname, isPrivatePath, nonce } = options;
  response.headers.set("X-Request-ID", requestId);
  response.headers.set("X-Content-Type-Options", "nosniff");
  response.headers.set("Referrer-Policy", pathname === "/auth/callback" ? "no-referrer" : "strict-origin-when-cross-origin");
  response.headers.set("X-Frame-Options", "DENY");
  response.headers.set("Cross-Origin-Resource-Policy", "same-origin");
  response.headers.set("Cross-Origin-Opener-Policy", "same-origin");
  response.headers.set("X-Permitted-Cross-Domain-Policies", "none");
  response.headers.set("Permissions-Policy", "camera=(), microphone=(), geolocation=()");
  if (process.env.NODE_ENV === "production") {
    response.headers.set("Strict-Transport-Security", "max-age=31536000");
    if (nonce) response.headers.set("Content-Security-Policy", buildContentSecurityPolicy(nonce));
  }
  if (isPrivatePath) privateHeaders(response);
  return response;
}

export function proxy(request: NextRequest) {
  const requestId = randomUUID();
  const pathname = request.nextUrl.pathname;
  const isApi = pathname.startsWith("/api/");
  const isPrivatePath = isApi || pathname === "/student" || pathname.startsWith("/student/")
    || pathname === "/teacher" || pathname.startsWith("/teacher/")
    || pathname.startsWith("/auth/");
  const callerId = request.nextUrl.searchParams.get("request_id") ?? request.headers.get("x-request-id");
  const clientRequestId = callerId && UUID_PATTERN.test(callerId) ? callerId.toLowerCase() : undefined;
  const nonce = process.env.NODE_ENV === "production" ? randomBytes(16).toString("base64") : null;

  if (isApi) {
    // Correlate without logging query strings, credentials, or request bodies.
    console.info("[api-request]", { requestId, clientRequestId, method: request.method, path: pathname });
  }

  if (isApi && MUTATING_METHODS.has(request.method)) {
    const origin = request.headers.get("origin");
    const fetchSite = request.headers.get("sec-fetch-site");
    // All first-party browser mutations submit Origin. Reject missing/mismatched Origin and cross-site fetches.
    if (!origin || origin !== request.nextUrl.origin || fetchSite === "cross-site") {
      const blocked = NextResponse.json({ error: "This request must come from the SNHS Gradebook website." }, { status: 403 });
      return applySecurityHeaders(blocked, { requestId, pathname, isPrivatePath, nonce });
    }
  }

  if (isApi && request.headers.get("sec-fetch-site") === "cross-site") {
    const blocked = NextResponse.json({ error: "Cross-site API access is not allowed." }, { status: 403 });
    return applySecurityHeaders(blocked, { requestId, pathname, isPrivatePath, nonce });
  }

  const requestHeaders = new Headers(request.headers);
  requestHeaders.set("x-request-id", requestId);
  if (nonce) {
    const csp = buildContentSecurityPolicy(nonce);
    // Next reads this request header and automatically adds the nonce to its rendered scripts.
    requestHeaders.set("Content-Security-Policy", csp);
    requestHeaders.set("x-nonce", nonce);
  }

  const response = NextResponse.next({ request: { headers: requestHeaders } });
  return applySecurityHeaders(response, { requestId, pathname, isPrivatePath, nonce });
}

